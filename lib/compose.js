const ORDER = ["izh", "vzd", "tyazh", "zap", "stul", "sweet"];
const ACC = { izh: "изжогу", vzd: "вздутие", tyazh: "тяжесть после еды", zap: "запоры", stul: "нестабильный стул", sweet: "тягу к сладкому" };
const GEN = { izh: "изжоги", vzd: "вздутия", tyazh: "тяжести", zap: "запоров", stul: "нестабильного стула", sweet: "тяги к сладкому" };

export function compose(j) {
  if (!j || j.plate === false) return NO_PLATE;

  const lines = [];
  lines.push(HEADER);
  lines.push("");
  lines.push("🍽 " + cap(slot(j.dish, "Ваша тарелка").replace(/\s*,\s*$/, "")) + ".");
  lines.push("");

  const counts = { red: 0, yellow: 0, green: 0 };
  const syms = new Set();
  for (let i = 1; i <= 9; i++) {
    const c = (j.criteria && j.criteria[String(i)]) || j["c" + i] || {};
    const st = norm(c.status);
    counts[st]++;
    let text;
    try { text = BANK[i][st](c); } catch { text = BANK[i][st]({}); }
    lines.push(`${ST[st]} ${BANK[i].name} — ${text}`);
    if (st === "red") {
      const s = (i === 4 && c.variant === "B") ? ["vzd"] : SYM[i];
      s.forEach(x => syms.add(x));
    }
  }

  lines.push("");
  lines.push(`Итог: 🔴 ${counts.red} из 9 пунктов требуют внимания, 🟡 ${counts.yellow} — с нюансами, 🟢 ${counts.green} — в порядке.`);
  lines.push("");

  if (counts.red > 0) {
    const ordered = ORDER.filter(x => syms.has(x));
    lines.push(`Именно красные пункты дают ${joinList(ordered.map(x => ACC[x]))}.`);
    lines.push("");
    const top = joinList(ordered.slice(0, 3).map(x => GEN[x]));
    const cta = slot(j.cta_product);
    lines.push(cta
      ? `Чем заменить ${cta} и как собрать тарелку, после которой нет ${top}, — без голода и жёстких диет — расскажем на бесплатном вебинаре: ${LINK}`
      : `Как собрать тарелку, после которой нет ${top}, — без голода и жёстких диет — расскажем на бесплатном вебинаре: ${LINK}`);
  } else {
    lines.push(`Эта тарелка не провоцирует ни изжогу, ни вздутие, ни тяжесть — отличный выбор. Как так же собрать весь рацион — расскажем на бесплатном вебинаре: ${LINK}`);
  }

  const sp = j.special;
  if (sp && typeof sp === "object") {
    let t = null;
    if (sp.kind === "child") t = "Для детей рацион подбирается индивидуально с врачом — этот разбор его не заменяет.";
    else if (sp.kind === "pregnancy") t = "При беременности рацион подбирается индивидуально с врачом — этот разбор его не заменяет.";
    else if (sp.kind === "diagnosis") t = `При ${slot(sp.label_prep, "заболеваниях ЖКТ")} рацион подбирается индивидуально с врачом — этот разбор его не заменяет.`;
    if (t) { lines.push(""); lines.push(t); }
  }

  lines.push("");
  lines.push(DISCLAIMER);
  return lines.join("\n");
}

// Достаём JSON из ответа модели (на случай, если она обернула его в ```).
export function parseModelJson(text) {
  if (!text) return null;
  try { return JSON.parse(text); } catch {}
  const fence = text.match(/```(?:json)?\s*([\s\S]*?)```/);
  if (fence) { try { return JSON.parse(fence[1]); } catch {} }
  const a = text.indexOf("{"), b = text.lastIndexOf("}");
  if (a >= 0 && b > a) { try { return JSON.parse(text.slice(a, b + 1)); } catch {} }
  return null;
}
